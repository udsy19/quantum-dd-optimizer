def test_generated_divergence_detected_and_sync_fixes_only_the_block(tree):
    original = tex(tree).read_text()
    edit(tree, r"\newcommand{\FixValue}{0.123}", r"\newcommand{\FixValue}{0.999}")
    edit(tree, "Second main page.", "Second main page, hand-edited prose.")
    out = errors(tree)
    assert "generated block report/generated/numbers.tex diverges" in out
    assert "-\\newcommand{\\FixValue}{0.123}" in out and "+\\newcommand{\\FixValue}{0.999}" in out

    r = run_cli("--root", str(tree), "sync-generated")           # dry run = divergence check
    assert r.returncode == 1 and "0.999" in r.stdout
    assert "0.999" in tex(tree).read_text()                        # not written without --write

    r = run_cli("--root", str(tree), "sync-generated", "--write")
    assert r.returncode == 0, r.stderr
    fixed = tex(tree).read_text()
    assert fixed == original.replace("Second main page.", "Second main page, hand-edited prose.")
    assert ms.check(tree) == []
    assert run_cli("--root", str(tree), "sync-generated").returncode == 0


