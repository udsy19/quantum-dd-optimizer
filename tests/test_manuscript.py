# ----------------------------------------------------------------------------- zip
def test_overleaf_zip_contents_exact_and_deterministic(tree, tmp_path):
    out1, out2 = tmp_path / "a.zip", tmp_path / "b.zip"
    assert run_cli("--root", str(tree), "zip", "--out", str(out1)).returncode == 0
    assert run_cli("--root", str(tree), "zip", "--out", str(out2)).returncode == 0
    assert out1.read_bytes() == out2.read_bytes()
    with zipfile.ZipFile(out1) as z:
        names = z.namelist()
        assert names == sorted(names)
        assert set(names) == {"merged.tex", "refs.bib", "figures/fig_a.pdf", "figures/fig_b.pdf", "README.txt"}
        assert [n for n in names if n.endswith(".tex")] == ["merged.tex"]
        assert z.read("merged.tex") == tex(tree).read_bytes()
        assert all(i.date_time == (1980, 1, 1, 0, 0, 0) for i in z.infolist())
        assert "main document" in z.read("README.txt").decode()
    out3 = tmp_path / "c.zip"
    assert run_cli("--root", str(tree), "zip", "--no-readme", "--out", str(out3)).returncode == 0
    with zipfile.ZipFile(out3) as z:
        assert "README.txt" not in z.namelist()


