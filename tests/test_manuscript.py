# ----------------------------------------------------------------------------- LaTeX builds
def latexmk(cwd: Path, target: str) -> None:
    r = subprocess.run(["latexmk", "-pdf", "-halt-on-error", "-interaction=nonstopmode", target],
                       cwd=cwd, capture_output=True, text=True)
    assert r.returncode == 0, r.stdout[-3000:] + r.stderr[-2000:]


@needs_tex
def test_compile_split_and_combined_completeness(tree):
    rep = tree / "report"
    latexmk(rep, "merged.tex")
    assert ms.check_log(rep / "merged.log") == []
    assert ms.supp_start_page(rep / "merged.aux") == 3
    r = run_cli("split", "--pdf", str(rep / "merged.pdf"), "--aux", str(rep / "merged.aux"),
                "--main", str(rep / "main.pdf"), "--supp", str(rep / "appendix.pdf"))
    assert r.returncode == 0, r.stderr
    n_all, n_main, n_supp = (ms.pdf_pages(rep / f) for f in ("merged.pdf", "main.pdf", "appendix.pdf"))
    assert (n_all, n_main, n_supp) == (4, 2, 2)
    assert n_main + n_supp == n_all
    # page limit enforcement
    r = run_cli("split", "--pdf", str(rep / "merged.pdf"), "--aux", str(rep / "merged.aux"),
                "--main", str(rep / "m2.pdf"), "--supp", str(rep / "a2.pdf"), "--max-main-pages", "1")
    assert r.returncode == 1 and "hard maximum: 1" in r.stderr


