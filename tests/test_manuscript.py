WORKFLOWS = ROOT / ".github" / "workflows"


def _code_lines(path: Path) -> str:
    return "\n".join(ln for ln in path.read_text().splitlines() if not ln.lstrip().startswith("#"))


def test_build_script_never_writes_merged_tex():
    sh = _code_lines(ROOT / "scripts" / "build_report.sh")
    assert "make_merged_overleaf" not in sh
    assert "sync-generated" not in sh
    assert not re.search(r">\s*\"?\$?\{?REPORT\}?/merged\.tex", sh)
    assert not re.search(r"\bgit\s+(add|commit|push)", sh)
    # the only cp of merged.tex copies it *out* of report/ (to temp dirs)
    for m in re.finditer(r"\bcp\b[^\n]*merged\.tex[^\n]*", sh):
        assert "$TMP" in m.group(0), m.group(0)
    assert "merged.tex changed during the build" in sh   # explicit hash guard


@pytest.mark.parametrize("wf", ["ci.yml", "release.yml", "pages.yml"])
def test_workflows_never_commit_or_write_manuscript(wf):
    y = _code_lines(WORKFLOWS / wf)
    assert not re.search(r"\bgit\s+(add|commit|push)\b", y), wf
    assert "make_merged_overleaf" not in y
    assert "sync-generated --write" not in y
    assert not re.search(r"(>|cp [^\n]*|mv [^\n]*)\s+report/merged\.tex", y)


def test_ci_permissions_and_concurrency():
    y = _code_lines(WORKFLOWS / "ci.yml")
    assert re.search(r"^permissions:\s*\n\s+contents:\s*read\s*$", y, re.M)
    assert "contents: write" not in y
    assert re.search(r"^concurrency:\s*\n\s+group:\s*ci-\$\{\{\s*github\.ref\s*\}\}\s*\n\s+cancel-in-progress:\s*true",
                     y, re.M)
    assert "report/merged.tex" in y and "report/main.tex" not in y
    assert "Sync editable Overleaf source" not in y
    for f in ("merged.tex", "merged.pdf", "combined_report.pdf", "main.pdf", "appendix.pdf",
              "overleaf-project.zip", "merged.log"):
        assert f"report/{f}" in y, f
    assert "if-no-files-found: error" in y


