def tex(tree: Path) -> Path:
    return tree / "report" / "merged.tex"


def edit(tree: Path, old: str, new: str) -> None:
    t = tex(tree).read_text()
    assert old in t, old
    tex(tree).write_text(t.replace(old, new, 1))


def errors(tree: Path) -> str:
    return "\n".join(ms.check(tree))


def run_cli(*args: str, cwd: Path | None = None) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(SCRIPT), *args], capture_output=True, text=True, cwd=cwd)


