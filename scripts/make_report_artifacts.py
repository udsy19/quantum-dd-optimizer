def fmt(x: float, d: int = 2) -> str:
    """Scientific notation for LaTeX, e.g. 1.23\\times10^{-2}."""
    if x == 0 or not math.isfinite(x):
        return str(x)
    e = int(math.floor(math.log10(abs(x))))
    return f"{x / 10 ** e:.{d}f}\\times10^{{{e}}}"


def m3(x: float) -> str:
    """value in units of 1e-3 with 3 significant figures"""
    v = x * 1e3
    return f"{v:.1f}" if v >= 10 else (f"{v:.2f}" if v >= 1 else f"{v:.3f}")


def macro(name: str, value: str, claim: str, run: dict, section: str, seed="") -> None:
    MACROS[name] = value
    CLAIMS.append({"claim_id": f"GEN-{name}", "paper_section": section, "exact_claim": claim,
                   "provenance_type": "model", "artifact_path": f"results/{run['run_id']}/payload.json",
                   "command": "python " + run["manifest"].get("command_str", ""),
                   "commit_sha": (run["manifest"].get("git", {}).get("sha") or "")[:12]
                   + ("+dirty" if run["manifest"].get("git", {}).get("dirty") else ""),
                   "run_id": run["run_id"], "seed": seed, "reviewer": "PENDING",
                   "verification_status": "UNVERIFIED"})


def save(fig, name: str) -> None:
    FIG.mkdir(exist_ok=True)
    fig.savefig(FIG / f"{name}.pdf", metadata={"CreationDate": None})
    fig.savefig(FIG / f"{name}.png", dpi=200)
    plt.close(fig)


def write(name: str, text: str) -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    if "\\begin{table}[t]" in text:  # single-column table: scale to the column if too wide
        text = text.replace("\\begin{tabular}", "\\resizebox{\\columnwidth}{!}{\\begin{tabular}").replace(
            "\\end{tabular}", "\\end{tabular}}")
    text = text.replace("\\texttt{", "\\runid{")
    # No commit stamp: the output depends only on the runs pinned in report/runs.json, so regenerating
    # at a later commit is byte-identical and report/merged.tex can embed it verbatim (see
    # scripts/manuscript.py check).
    (GEN / name).write_text(f"% GENERATED by {CMD} from report/runs.json; do not edit.\n" + text)


