def bench_summary(run: dict) -> dict:
    """{n: {"baselines": {name: (mean, sd)}, "modes": {mode: [ratio_per_trainrun...]}, ...}}"""
    out: dict = {}
    for r in run["payload"]["runs"]:
        e = out.setdefault(r["n"], {"baselines": {}, "modes": {}, "selected": r["selected_baseline"],
                                    "omitted": r.get("baselines_omitted", {}), "T": r["T"]})
        for k, v in r["test"]["summary"].items():
            if k != "optimized":
                e["baselines"][k] = v["mean_over_seeds"]
        p = r["comparison_vs_selected"]["pooled"]
        e["modes"].setdefault(r["mode"], []).append(
            {"eps_opt": p["eps_b"], "eps_sel": p["eps_a"], "ratio": p["ratio"], "ratio_ci": p["ratio_ci"],
             "train_opt": r["train_test_gap"]["optimized"]["train"], "train_seed": r["seeds"]["train"],
             "n_evals": r["optimization"]["n_evaluations"]})
        if e["selected"] != r["selected_baseline"]:
            raise RuntimeError("selected baseline differs between training runs at same n")
    return out


def bench_table(summ: dict, label: str, caption: str, fname: str) -> None:
    rows = []
    for n, e in sorted(summ.items()):
        b = e["baselines"]
        best = e["selected"]
        cells = []
        for k in ("free", "cpmg", "xy4", "xy8", "udd"):
            cells.append(f"${fmt(b[k])}$" if k in b else "---")
        mode_cells = []
        for m in ("timing", "phase", "both"):
            rs = e["modes"].get(m, [])
            if not rs:
                mode_cells.append("---")
                continue
            ratios = [x["ratio"] for x in rs]
            lo = min(x["ratio_ci"][0] for x in rs)
            hi = max(x["ratio_ci"][1] for x in rs)
            mode_cells.append(f"${fmt(float(np.mean([x['eps_opt'] for x in rs])))}$ "
                              f"({min(ratios):.3f}--{max(ratios):.3f}; [{lo:.3f},{hi:.3f}])")
        rows.append(f"{n} & {' & '.join(cells)} & {best.upper()} & " + " & ".join(mode_cells) + r" \\")
    write(fname, r"""\begin{table*}[t]
\centering\scriptsize
\caption{%s}
\label{%s}
\begin{tabular}{@{}c ccccc c ccc@{}}\toprule
 & \multicolumn{5}{c}{Canonical baselines, test $\epsilon$} & Selected & \multicolumn{3}{c}{CMA-ES test $\epsilon$ (ratio range; pooled 95\%% CI envelope)}\\
\cmidrule(lr){2-6}\cmidrule(lr){8-10}
$n$ & Free & CPMG & XY4 & XY8 & UDD & (train rule) & timing-only & phase-only & timing+phase\\\midrule
%s
\bottomrule\end{tabular}\end{table*}
""" % (caption, label, "\n".join(rows)))


def bench_figure(summs: dict[str, dict], floors: dict[str, float], name: str) -> None:
    fig, axes = plt.subplots(1, len(summs), figsize=(7.0, 2.6), sharey=True)
    axes = np.atleast_1d(axes)
    for ax, (title, summ) in zip(axes, summs.items()):
        ns = sorted(summ)
        xs = np.arange(len(ns))
        fams = ["free", "cpmg", "xy4", "xy8", "udd"]
        width = 0.11
        for j, k in enumerate(fams + ["opt_both", "opt_phase"]):
            ys, xx = [], []
            for i, n in enumerate(ns):
                e = summ[n]
                if k.startswith("opt_"):
                    rs = e["modes"].get(k[4:], [])
                    if rs:
                        ys.append(np.mean([x["eps_opt"] for x in rs]))
                        xx.append(xs[i] + (j - 3) * width)
                elif k in e["baselines"]:
                    ys.append(e["baselines"][k])
                    xx.append(xs[i] + (j - 3) * width)
            key = "optimized" if k.startswith("opt_") else k
            lab = (f"CMA-ES {MODE_LABEL[k[4:]]}" if k.startswith("opt_") else LABEL[k])
            ax.scatter(xx, ys, s=22 if key != "optimized" else 40, marker=MARKERS[key] if k != "opt_phase" else "P",
                       color=COLORS[key], label=lab, zorder=3, edgecolor="white", linewidth=0.5)
        ax.axhline(floors[title], color="#55554f", ls="--", lw=1)
        ax.text(-0.45, floors[title] * 1.06, "$T_1$ + white-noise floor", ha="left", va="bottom", fontsize=7,
                color="#55554f")
        ax.set_xticks(xs, [f"n={n}" for n in ns])
        ax.set_yscale("log")
        ax.set_title(title, fontsize=8)
    axes[0].set_ylabel(r"held-out infidelity $\epsilon$ (mean over 5 test seeds)")
    axes[-1].legend(loc="upper left", bbox_to_anchor=(1.0, 1.0), fontsize=7)
    save(fig, name)


def feasibility(cfg: dict) -> None:
    w = cfg["window"]
    rows = []
    for T in (w["T"], w["T_alt"]):
        for n in (4, 8, 16):
            om: dict = {}
            bl = canonical_baselines(n, T, w["width"], guard=w["guard"], dt_grid=w["dt_grid"], omitted=om)
            for fam in ("cpmg", "xy4", "xy8", "udd"):
                if fam in bl:
                    s = bl[fam]
                    nominal = getattr(sequences, fam)(n, T, w["width"], guard=w["guard"])
                    err = max(abs(a - b) for a, b in zip(s.centers, nominal.centers)) if s.n else 0.0
                    ming = float(np.min(s.gaps()))
                    rows.append(f"{T*1e6:.0f} & {n} & {fam.upper()} & yes & {err*1e9:.1f} & {ming*1e9:.0f} \\\\")
                elif not om.get(fam, "").startswith("not applicable"):
                    rows.append(f"{T*1e6:.0f} & {n} & {fam.upper()} & no$^\\dagger$ & --- & --- \\\\")
    # explicit refusal example from the master prompt
    try:
        sequences.cpmg(16, 500e-9, 40e-9)
        refused = "accepted (UNEXPECTED)"
    except ValueError:
        refused = "refused"
    write("feasibility_table.tex", r"""\begin{table}[t]
\centering\scriptsize
\caption{Timing feasibility, square $\pi$ pulses $w=%g$\,ns, guard %g\,ns, pulse starts snapped to a
%g\,ns grid (assumed controller tick). ``Shift'' = largest change of a pulse centre caused by grid
snapping; ``min gap'' = smallest free gap. $^\dagger$UDD-16 edge pulses violate the guard after
snapping. Control check: 16$\times$40\,ns pulses in a 500\,ns window is %s by validation.}
\label{tab:feasibility}
\begin{tabular}{@{}cclccc@{}}\toprule
$T$ ($\mu$s) & $n$ & Family & Feasible & Shift (ns) & Min gap (ns)\\\midrule
%s
\bottomrule\end{tabular}\end{table}
""" % (w["width"] * 1e9, w["guard"] * 1e9, w["dt_grid"] * 1e9, refused, "\n".join(rows)))


def convergence(run: dict) -> None:
    p = run["payload"]
    fig, ax = plt.subplots(figsize=(3.4, 2.4))
    for (mode, base), color, mk in ((("both", "cpmg"), COLORS["optimized"], "*"), (("timing", "xy"), COLORS["udd"], "D")):
        rs = sorted([r for r in p["rows"] if r["mode"] == mode and r["base_phases"] == base], key=lambda r: r["budget"])
        b = [r["n_evaluations"] for r in rs]
        lab = "timing+phase (from CPMG)" if mode == "both" else "timing-only (XY phases)"
        ax.plot(b, [r["train"] for r in rs], color=color, ls="--", marker=mk, ms=4, label=f"{lab}: train")
        ax.plot(b, [np.mean(r["val_per_seed"]) for r in rs], color=color, marker=mk, ms=4, label=f"{lab}: validation")
    best = min(("xy4", "xy8"), key=lambda k: np.mean(p["baselines"][k]["val_per_seed"]))
    ax.axhline(np.mean(p["baselines"][best]["val_per_seed"]), color=COLORS[best], lw=1,
               label=f"{LABEL[best]} validation")
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("CMA-ES objective evaluations")
    ax.set_ylabel(r"infidelity $\epsilon$")
    ax.legend(fontsize=6)
    save(fig, "fig_convergence")
    last = [r for r in p["rows"] if r["mode"] == "both" and r["budget"] == max(x["budget"] for x in p["rows"])][0]
    macro("ConvTrainFinal", f"{fmt(last['train'])}", "convergence n=8 timing+phase final training infidelity", run, "Results")
    macro("ConvValFinal", f"{fmt(float(np.mean(last['val_per_seed'])))}", "convergence n=8 timing+phase final validation infidelity (seeds 8001-8002)", run, "Results")
    macro("ConvBestBaselineVal", f"{fmt(float(np.mean(p['baselines'][best]['val_per_seed'])))}", f"convergence n=8: {best} validation infidelity", run, "Results")


def scen_b(run: dict) -> None:
    runs = [r for r in run["payload"]["runs"] if "scenario_b_robustness" in r]
    # pick the pre-registered arm summary at each n from the first training run (arms 1-3 are
    # independent of the training run; arm 4 depends on it: report all three)
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.4), sharey=True)
    n_show = 8
    rs = [r for r in runs if r["n"] == n_show and r["mode"] == "both"]
    for ax, key, xlabel, xs, fx in (
        (axes[0], "amp", "Stark amplitude / nominal", [0.8, 0.9, 1.0, 1.1, 1.2], lambda v: f"amp_x{v}"),
        (axes[1], "shift", "readout timing shift (ns)", [-100, -50, 0, 50, 100], None),
    ):
        rob = rs[0]["scenario_b_robustness"]
        keys = [k for k in rob if k.startswith(key)] or []
        # sort keys by their numeric value
        def val(k):
            return float(k.split("_")[-1].replace("x", "").replace("ns", "").replace("p", "."))
        keys = sorted(keys, key=val)
        arms = list(rob[keys[0]]["summary"])
        for arm in arms:
            ys = [rob[k]["summary"][arm]["mean_over_seeds"] for k in keys]
            col = {"1": COLORS["free"], "2": COLORS["cpmg"], "3": COLORS["xy4"], "4": COLORS["optimized"]}[arm[0]]
            ax.plot([val(k) for k in keys], ys, marker="o", ms=3, color=col, label={"1": "no DD, no frame correction", "2": "virtual-Z only", "3": "best canonical DD + virtual-Z",
                                                        "4": "CMA-ES DD + virtual-Z"}[arm[0]])
        ax.set_xlabel(xlabel)
        ax.set_yscale("log")
    axes[0].set_ylabel(r"held-out $\epsilon$ (n=%d)" % n_show)
    axes[1].legend(fontsize=6, loc="upper left", bbox_to_anchor=(1.0, 1.0))
    save(fig, "fig_robustness_b")


