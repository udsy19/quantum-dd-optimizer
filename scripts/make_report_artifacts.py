def floor_infidelity(cfg: dict, T: float) -> float:
    """Non-decouplable floor: amplitude damping over T composed with white dephasing (chi=S0*T).
    (White noise filter weight is pulse-independent for instantaneous pulses.)"""
    nm = scenario_noise(cfg)
    S0 = sum(c.params["S0"] for c in nm.components if c.kind == "white")
    R = channels.compose_ptm(channels.dephasing_ptm(math.exp(-S0 * T / 2)),
                             channels.amplitude_damping_ptm(channels.gamma_from_T1(T, nm.T1)))
    return 1 - channels.avg_gate_fidelity_ptm(R)


