def bench_figure(summs: dict[str, dict], floors: dict[str, float], name: str) -> None:
    """Absolute held-out infidelity of every arm, including timing-only CMA-ES (supplement)."""
    fig, axes = plt.subplots(1, len(summs), figsize=(PAGE_W - 1.45, 2.5), sharey=True)
    axes = np.atleast_1d(axes)
    keys = ["free", "cpmg", "xy4", "xy8", "udd", "opt_timing", "opt_phase", "opt_both"]
    width = 0.1
    for ax, (title, summ) in zip(axes, summs.items()):
        ns = sorted(summ)
        xs = np.arange(len(ns))
        for j, k in enumerate(keys):
            ys, xx = [], []
            for i, n in enumerate(ns):
                e = summ[n]
                if k.startswith("opt_"):
                    rs = e["modes"].get(k[4:], [])
                    if rs:
                        ys.append(np.mean([x["eps_opt"] for x in rs]))
                        xx.append(xs[i] + (j - 3.5) * width)
                elif k in e["baselines"]:
                    ys.append(e["baselines"][k])
                    xx.append(xs[i] + (j - 3.5) * width)
            key = "optimized" if k.startswith("opt_") else k
            lab = f"CMA-ES {MODE_LABEL[k[4:]]}" if k.startswith("opt_") else LABEL[k]
            mk = {"opt_timing": "X", "opt_phase": "P", "opt_both": "*"}.get(k, MARKERS[key])
            col = {"opt_timing": "#7a7a74", "opt_phase": COLORS["udd"]}.get(k, COLORS[key])
            ax.scatter(xx, ys, s=40 if k == "opt_both" else 26, marker=mk, color=col, label=lab, zorder=3,
                       edgecolor="white", linewidth=0.4)
        ax.axhline(floors[title], color="#55554f", ls="--", lw=1)
        ax.text(-0.45, floors[title] * 0.96, "$T_1$ + white-noise floor", ha="left", va="top", fontsize=7.5,
                color="#55554f")
        ax.set_ylim(floors[title] * 0.78, None)
        ax.set_xticks(xs, [f"$n={n}$" for n in ns])
        ax.set_yscale("log")
        ax.set_title(title)
    axes[0].set_ylabel(r"held-out infidelity $\epsilon$")
    axes[-1].legend(loc="upper left", bbox_to_anchor=(1.0, 1.02), handletextpad=0.2)
    save(fig, name)


def bench_ratio_figure(summs: dict[str, dict], name: str) -> None:
    """Ratio eps_selected / eps_CMA with the pooled paired-bootstrap 95% interval, per training run.

    Timing-only CMA-ES is not drawn: its ratios are far below 1 (see the benchmark table)."""
    fig, axes = plt.subplots(1, len(summs), figsize=(COL_W, 2.45), sharey=True)
    axes = np.atleast_1d(axes)
    style = {"phase": (COLORS["udd"], "P", -0.17), "both": (COLORS["optimized"], "*", 0.17)}
    for ax, (title, summ) in zip(axes, summs.items()):
        ns = sorted(summ)
        ax.axhline(1.0, color="#55554f", lw=1, ls="--", zorder=1)
        for i, n in enumerate(ns):
            for mode, (col, mk, off) in style.items():
                rs = sorted(summ[n]["modes"].get(mode, []), key=lambda x: x["train_seed"])
                for k, x in enumerate(rs):
                    xpos = i + off + (k - 1) * 0.08
                    err = [[x["ratio"] - x["ratio_ci"][0]], [x["ratio_ci"][1] - x["ratio"]]]
                    ax.errorbar([xpos], [x["ratio"]], yerr=err, fmt=mk, color=col,
                                ms=5.5 if mode == "both" else 4.5, elinewidth=0.9, capsize=1.5,
                                mec="white", mew=0.3, zorder=3,
                                label=f"CMA-ES {MODE_LABEL[mode]}" if (i == 0 and k == 0) else None)
        ax.set_xticks(range(len(ns)), [f"$n={n}$\n{sel_label(summ[n])}" for n in ns])
        ax.set_xlim(-0.5, len(ns) - 0.5)
        ax.set_title(title)
        ax.grid(axis="x", visible=False)
    axes[0].set_ylabel(r"$\epsilon_{\rm sel}/\epsilon_{\rm CMA}$ ($>$1 favours CMA-ES)")
    h, lab = axes[0].get_legend_handles_labels()
    fig.legend(h, lab, loc="lower center", ncol=2, bbox_to_anchor=(0.55, -0.04), handletextpad=0.2,
               columnspacing=1.2)
    fig.tight_layout(rect=(0, 0.07, 1, 1), w_pad=0.6)
    save(fig, name)


def feasibility(cfg: dict) -> None:
    w = cfg["window"]
    rows = []
    for T in (w["T"], w["T_alt"]):
        for n in (4, 8, 16):
            om: dict = {}
            bl = canonical_baselines(n, T, w["width"], guard=w["guard"], dt_grid=w["dt_grid"], omitted=om)
            ok, bad, shifts, gaps = [], [], [], []
            for fam in ("cpmg", "xy4", "xy8", "udd"):
                if fam in bl:
                    sq = bl[fam]
                    nominal = getattr(sequences, fam)(n, T, w["width"], guard=w["guard"])
                    shifts.append(max(abs(a - b) for a, b in zip(sq.centers, nominal.centers)))
                    gaps.append(float(np.min(sq.gaps())))
                    ok.append(fam.upper())
                elif not om.get(fam, "").startswith("not applicable"):
                    bad.append(fam.upper())
            rows.append(f"{T*1e6:.0f} & {n} & {', '.join(ok)} & {', '.join(bad) or '---'} & {max(shifts)*1e9:.1f} & {min(gaps)*1e9:.0f} \\\\")
    # explicit refusal example from the master prompt
    try:
        sequences.cpmg(16, 500e-9, 40e-9)
        refused = "accepted (UNEXPECTED)"
    except ValueError:
        refused = "refused"
    write("feasibility_table.tex", r"""\begin{table}[t]
\centering\scriptsize
\caption{Timing feasibility, square $\pi$ pulses $w=%g$\,ns, guard %g\,ns, pulse starts snapped to a
%g\,ns grid (assumed controller tick). ``Shift'' = largest change of a pulse centre caused by grid
snapping; ``min gap'' = smallest free gap over feasible families. Infeasible: edge pulses violate the guard after
snapping. Control check: 16$\times$40\,ns pulses in a 500\,ns window is %s by validation.}
\label{tab:feasibility}
\begin{tabular}{@{}cclccc@{}}\toprule
$T$ ($\mu$s) & $n$ & Feasible & Infeasible & Max shift (ns) & Min gap (ns)\\\midrule
%s
\bottomrule\end{tabular}\end{table}
""" % (w["width"] * 1e9, w["guard"] * 1e9, w["dt_grid"] * 1e9, refused, "\n".join(rows)))


def convergence(run: dict) -> None:
    p = run["payload"]
    fig, ax = plt.subplots(figsize=(COL_W, 2.6))
    for (mode, base), color, mk in ((("both", "cpmg"), COLORS["optimized"], "*"), (("timing", "xy"), COLORS["udd"], "D")):
        rs = sorted([r for r in p["rows"] if r["mode"] == mode and r["base_phases"] == base], key=lambda r: r["budget"])
        b = [r["n_evaluations"] for r in rs]
        # The stored run records base_phases: timing+phase starts from CPMG (Y axes) as in the
        # pre-registered benchmark; the timing-only curve is a different, exploratory configuration
        # that keeps XY8 phases fixed (the pre-registered timing-only arm keeps CPMG-Y phases).
        lab = "timing+phase (CPMG start)" if mode == "both" else "timing-only (XY8 phases)"
        ax.plot(b, [r["train"] for r in rs], color=color, ls="--", marker=mk, ms=4, label=f"{lab}: train")
        ax.plot(b, [np.mean(r["val_per_seed"]) for r in rs], color=color, marker=mk, ms=4, label=f"{lab}: validation")
    best = min(("xy4", "xy8"), key=lambda k: np.mean(p["baselines"][k]["val_per_seed"]))
    ax.axhline(np.mean(p["baselines"][best]["val_per_seed"]), color=COLORS[best], lw=1,
               label=f"{LABEL[best]} validation")
    ax.axhline(p["baselines"][best]["train"], color=COLORS[best], lw=1, ls="--", label=f"{LABEL[best]} train")
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("CMA-ES objective evaluations")
    ax.set_ylabel(r"infidelity $\epsilon$")
    ax.legend(loc="upper center", bbox_to_anchor=(0.42, -0.22), ncol=2, columnspacing=0.8, handlelength=2.0)
    save(fig, "fig_convergence")
    last = [r for r in p["rows"] if r["mode"] == "both" and r["budget"] == max(x["budget"] for x in p["rows"])][0]
    macro("ConvTrainFinal", f"{fmt(last['train'])}", "convergence n=8 timing+phase final training infidelity", run, "Results")
    macro("ConvValFinal", f"{fmt(float(np.mean(last['val_per_seed'])))}", "convergence n=8 timing+phase final validation infidelity (seeds 8001-8002)", run, "Results")
    macro("ConvBestBaselineVal", f"{fmt(float(np.mean(p['baselines'][best]['val_per_seed'])))}", f"convergence n=8: {best} validation infidelity", run, "Results")
    macro("ConvBestBaselineTrain", f"{fmt(p['baselines'][best]['train'])}", f"convergence n=8: {best} training infidelity", run, "Results")
    tx = max((r for r in p["rows"] if r["mode"] == "timing" and r["base_phases"] == "xy"), key=lambda r: r["budget"])
    macro("ConvTimingXYTrainFinal", f"{fmt(tx['train'])}", "convergence n=8 timing-only from XY8 phases (exploratory): final training infidelity", run, "Results")
    macro("ConvTimingXYValFinal", f"{fmt(float(np.mean(tx['val_per_seed'])))}", "convergence n=8 timing-only from XY8 phases (exploratory): final validation infidelity (seeds 8001-8002)", run, "Results")


