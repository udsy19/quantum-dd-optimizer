"""SDK-free translator: ``PulseSequence`` -> hardware-agnostic clock-cycle schedule.

*** NOT HARDWARE TESTED ***

This module performs *pure bookkeeping*: it converts the idle-window schedule of a
:class:`ddopt.contracts.PulseSequence` (seconds, radians) into an ordered list of
``wait`` / ``frame_rotation_2pi`` / ``play`` instructions expressed in integer controller
clock cycles. It imports nothing from the Quantum Machines SDK, opens no connection and
cannot execute anything. A successful translation says **nothing** about whether the
schedule would compile, run, or behave as intended on any device.

Provenance of the timing / phase conventions used below
--------------------------------------------------------
VERIFIED (read from the docstrings of the official ``qm-qua`` 1.4.1 wheel from PyPI,
sha256 e6c70238...a87bb, accessed 2026-10-26; the docs site docs.quantum-machines.co was
not reachable from the build environment, see ``docs/HARDWARE_PROTOCOL.md``):

* ``wait(duration, *elements)``: "Duration is in units of the clock cycle (4ns)".
* ``play(pulse, element, duration=None, ...)``: ``duration`` is "in units of the clock
  cycle (4ns)"; arbitrary waveforms "can only be expanded up to 2^24-1 clock cycles".
* ``frame_rotation_2pi(angle, *elements)``: "Shift the phase of the oscillator associated
  with an element by the given angle in units of 2pi radians"; phase is "accumulated with a
  resolution of 16 bit".

ASSUMPTIONS (NOT verified from official documentation -- configurable, must be confirmed
against the vendor documentation / simulator for the actual QOP version before use):

* Minimum ``wait`` and minimum ``play`` duration of 4 clock cycles (16 ns).
* Frame rotations take zero time on the element's timeline (the SDK docstring for
  ``wait`` itself warns that additional computational latency may be added and that
  timing "should always be verified with a simulator").
* Phase sign convention (``AdapterConfig.frame_sign``): a cumulative element frame
  rotation of +theta makes the calibrated ``pi`` operation rotate about the Bloch axis
  ``cos(frame_sign*theta) X + sin(frame_sign*theta) Y``. **REQUIRES HARDWARE CALIBRATION**
  (depends on IQ mixer conventions, upconversion sideband and the element configuration).

Phase convention mapping (contract -> schedule)
-----------------------------------------------
The contract pulse k rotates about ``cos(phi_k) X + sin(phi_k) Y`` (``docs/PHYSICS_CONVENTIONS.md``).
The adapter tracks the cumulative frame ``theta`` (radians, starts at 0). Before pulse k it
emits ``frame_rotation_2pi(turns)`` with ``turns = wrap(frame_sign*phi_k - theta)/(2 pi)``,
wrap to (-pi, pi], whenever this is nonzero. At the end of the window the cumulative frame
is undone so the element frame is returned to its starting value (``restore_frame=True``).
An optional *target-frame* virtual-Z correction ``R_z(theta_vz)`` is then implemented as a
frame rotation of ``-frame_sign*theta_vz`` (common virtual-Z convention: a Z rotation of the
qubit by theta equals shifting the phase of all later drive pulses by -theta) -- also
**REQUIRES HARDWARE CALIBRATION**.
"""

from __future__ import annotations

import json
import math
from dataclasses import asdict, dataclass, field
from typing import Any, Literal

from ddopt.contracts import PulseSequence

NOT_HARDWARE_TESTED: bool = True
WATERMARK: str = (
    "NOT_HARDWARE_TESTED: generated by qua.adapter; never compiled, simulated or executed on "
    "any Quantum Machines / IQCC backend; placeholder element/operation names; timing and "
    "phase conventions partly ASSUMED (see docs/HARDWARE_PROTOCOL.md)"
)

#: Verified from qm-qua 1.4.1 docstrings (wait/play: "units of the clock cycle (4ns)").
QM_CLOCK_PERIOD_S: float = 4e-9
#: ASSUMPTION (not verified from official docs): 4 cycles = 16 ns minimum wait/pulse.
ASSUMED_MIN_WAIT_CYCLES: int = 4
ASSUMED_MIN_PULSE_CYCLES: int = 4
#: Verified from qm-qua 1.4.1 ``play`` docstring (arbitrary waveforms, stretch limit).
QM_MAX_PLAY_CYCLES: int = 2**24 - 1
#: Verified from qm-qua 1.4.1 ``frame_rotation_2pi`` docstring: 16-bit phase resolution.
QM_PHASE_RESOLUTION_TURNS: float = 2.0**-16

PLACEHOLDER_ELEMENT = "qubit_PLACEHOLDER"
PLACEHOLDER_PI_OPERATION = "pi_PLACEHOLDER"


class ScheduleRejected(ValueError):
    """The sequence cannot be represented on the assumed controller grid."""


@dataclass(frozen=True)
class AdapterConfig:
    """Translation settings. Defaults are *placeholders/assumptions*, not device facts."""

    clock_period_s: float = QM_CLOCK_PERIOD_S
    min_wait_cycles: int = ASSUMED_MIN_WAIT_CYCLES
    min_pulse_cycles: int = ASSUMED_MIN_PULSE_CYCLES
    max_play_cycles: int = QM_MAX_PLAY_CYCLES
    qubit_element: str = PLACEHOLDER_ELEMENT
    pi_operation: str = PLACEHOLDER_PI_OPERATION
    #: False (default): every pulse edge and T must already lie on the clock grid
    #: within ``grid_tol_s``; otherwise :class:`ScheduleRejected`. True: round each edge to
    #: the nearest cycle and report the rounding errors.
    allow_rounding: bool = False
    grid_tol_s: float = 1e-12
    #: When rounding, reject if any edge moves by more than this (seconds); None = no limit
    #: beyond the inherent half cycle.
    max_edge_error_s: float | None = None
    #: +1 or -1. REQUIRES HARDWARE CALIBRATION (see module docstring).
    frame_sign: Literal[1, -1] = 1
    restore_frame: bool = True
    #: Only calibrated pi rotations are supported (one placeholder operation).
    angle_tol_rad: float = 1e-9
    phase_tol_rad: float = 1e-12

    def validate(self) -> None:
        if not (self.clock_period_s > 0 and math.isfinite(self.clock_period_s)):
            raise ValueError("clock_period_s must be positive and finite")
        if self.min_wait_cycles < 1 or self.min_pulse_cycles < 1:
            raise ValueError("minimum cycle counts must be >= 1")
        if self.frame_sign not in (1, -1):
            raise ValueError("frame_sign must be +1 or -1")


@dataclass(frozen=True)
class Instruction:
    """One controller instruction on ``element``.

    kind:
      * ``wait``: idle for ``cycles`` clock cycles.
      * ``play``: play ``operation`` for ``cycles`` clock cycles (``duration`` argument).
        ``axis_phase_rad`` records the intended contract axis phase phi_k.
      * ``frame_rotation_2pi``: zero-duration (ASSUMED) frame shift by ``turns`` x 2pi rad.
    ``t_start_cycles`` is the scheduled start on the element timeline.
    """

    kind: Literal["wait", "play", "frame_rotation_2pi"]
    element: str
    t_start_cycles: int
    cycles: int = 0
    operation: str | None = None
    turns: float | None = None
    axis_phase_rad: float | None = None
    note: str = ""


@dataclass
class HardwareSchedule:
    """Translated schedule. Always carries the NOT_HARDWARE_TESTED watermark."""

    instructions: list[Instruction]
    total_cycles: int
    clock_period_s: float
    T_requested_s: float
    T_scheduled_s: float
    source_label: str
    rounding: dict[str, Any]
    warnings: list[str]
    assumptions: dict[str, str]
    config: dict[str, Any]
    NOT_HARDWARE_TESTED: bool = True
    watermark: str = WATERMARK
    source_metadata: dict[str, Any] = field(default_factory=dict)

    def timed_cycles(self) -> int:
        return sum(i.cycles for i in self.instructions if i.kind in ("wait", "play"))

    def check(self) -> None:
        """Internal consistency: durations add up to the window, timeline is contiguous."""
        t = 0
        for ins in self.instructions:
            if ins.t_start_cycles != t:
                raise AssertionError(f"timeline gap/overlap at {ins}")
            if ins.kind in ("wait", "play"):
                t += ins.cycles
        if t != self.total_cycles:
            raise AssertionError(f"instruction cycles {t} != total_cycles {self.total_cycles}")
        if not (self.NOT_HARDWARE_TESTED and self.watermark == WATERMARK):
            raise AssertionError("watermark removed")

    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        # Watermark first so it is the first thing any reader of the JSON sees.
        return {"NOT_HARDWARE_TESTED": True, "watermark": WATERMARK, **d}

    def to_json(self, **kw: Any) -> str:
        return json.dumps(self.to_dict(), **kw)

    def to_text(self) -> str:
        """Human-readable listing (pseudo-QUA, not executable)."""
        bar = "#" * 78
        lines = [bar, f"# {WATERMARK}", "# NOT HARDWARE TESTED -- pseudo-code listing, not a QUA program", bar,
                 f"# source: {self.source_label}; T_requested = {self.T_requested_s:.12g} s; "
                 f"T_scheduled = {self.T_scheduled_s:.12g} s = {self.total_cycles} cycles x "
                 f"{self.clock_period_s:.3g} s",
                 f"# max |edge rounding error| = {self.rounding['max_abs_edge_error_s']:.3g} s"]
        for w in self.warnings:
            lines.append(f"# WARNING: {w}")
        for ins in self.instructions:
            if ins.kind == "wait":
                lines.append(f"wait({ins.cycles}, '{ins.element}')  # t0={ins.t_start_cycles}")
            elif ins.kind == "play":
                lines.append(f"play('{ins.operation}', '{ins.element}', duration={ins.cycles})"
                             f"  # t0={ins.t_start_cycles}, axis phi={ins.axis_phase_rad:.6g} rad")
            else:
                lines.append(f"frame_rotation_2pi({ins.turns:.12g}, '{ins.element}')"
                             f"  # {ins.note} [sign REQUIRES HARDWARE CALIBRATION]")
        lines += [bar, "# NOT HARDWARE TESTED", bar]
        return "\n".join(lines)


def _wrap_pi(x: float) -> float:
    """Wrap an angle to (-pi, pi]."""
    y = math.fmod(x + math.pi, 2 * math.pi)
    if y <= 0:
        y += 2 * math.pi
    return y - math.pi


def _quantize(t: float, cfg: AdapterConfig, what: str) -> tuple[int, float]:
    q = t / cfg.clock_period_s
    c = int(round(q))
    err = c * cfg.clock_period_s - t
    if not cfg.allow_rounding and abs(err) > cfg.grid_tol_s:
        raise ScheduleRejected(
            f"{what} = {t:.12g} s is off the {cfg.clock_period_s:.3g} s clock grid "
            f"(nearest cycle {c}, error {err:.3g} s); pass allow_rounding=True to round explicitly"
        )
    if cfg.max_edge_error_s is not None and abs(err) > cfg.max_edge_error_s:
        raise ScheduleRejected(f"{what}: rounding error {err:.3g} s exceeds max_edge_error_s")
    return c, err


def to_schedule(
    seq: PulseSequence,
    config: AdapterConfig | None = None,
    *,
    virtual_z_angle: float | None = None,
) -> HardwareSchedule:
    """Translate ``seq`` into a clock-cycle :class:`HardwareSchedule`.

    Raises :class:`ScheduleRejected` for: zero-width (ideal) pulses, non-pi rotation
    angles, edges off the clock grid (unless ``allow_rounding``), free gaps that are
    nonzero but shorter than ``min_wait_cycles``, pulses shorter than ``min_pulse_cycles``
    or longer than ``max_play_cycles``, and guard violations introduced by rounding.

    ``virtual_z_angle``: optional target-frame correction theta_vz (rad) appended as a
    final frame rotation (sign REQUIRES HARDWARE CALIBRATION).
    """
    cfg = config or AdapterConfig()
    cfg.validate()
    seq.validate()
    dt = cfg.clock_period_s
    warnings: list[str] = []

    for k, w in enumerate(seq.widths):
        if w <= 0:
            raise ScheduleRejected(f"pulse {k} has width {w}: ideal instantaneous pulses are not realizable")
    for k, a in enumerate(seq.angles):
        if abs(a - math.pi) > cfg.angle_tol_rad:
            raise ScheduleRejected(
                f"pulse {k} angle {a} rad != pi: only a single calibrated pi operation is supported"
            )

    T_c, T_err = _quantize(seq.T, cfg, "T")
    edges_req: list[float] = []
    edges_c: list[int] = []
    edge_err: list[float] = []
    for k in range(seq.n):
        s = seq.centers[k] - seq.widths[k] / 2
        e = seq.centers[k] + seq.widths[k] / 2
        for t, nm in ((s, f"pulse {k} start"), (e, f"pulse {k} end")):
            c, err = _quantize(t, cfg, nm)
            edges_req.append(t)
            edges_c.append(c)
            edge_err.append(err)

    # Rebuild the timeline in integer cycles.
    bounds = [0] + edges_c + [T_c]
    gaps_c = [bounds[2 * i + 1] - bounds[2 * i] for i in range(seq.n + 1)]
    widths_c = [edges_c[2 * k + 1] - edges_c[2 * k] for k in range(seq.n)]
    for i, g in enumerate(gaps_c):
        if g < 0:
            raise ScheduleRejected(f"gap {i} negative ({g} cycles) after quantization: pulses overlap")
        if 0 < g < cfg.min_wait_cycles:
            raise ScheduleRejected(
                f"gap {i} = {g} cycles ({g * dt:.3g} s) is below the minimum wait of "
                f"{cfg.min_wait_cycles} cycles (ASSUMED {cfg.min_wait_cycles * dt:.3g} s)"
            )
        if seq.guard > 0 and g * dt < seq.guard - cfg.grid_tol_s:
            raise ScheduleRejected(f"gap {i} = {g * dt:.3g} s violates guard {seq.guard:.3g} s after quantization")
    for k, wc in enumerate(widths_c):
        if wc < cfg.min_pulse_cycles:
            raise ScheduleRejected(
                f"pulse {k} = {wc} cycles is below the minimum pulse length of {cfg.min_pulse_cycles} "
                f"cycles (ASSUMED)"
            )
        if wc > cfg.max_play_cycles:
            raise ScheduleRejected(f"pulse {k} = {wc} cycles exceeds max_play_cycles")
    if len(set(widths_c)) > 1:
        warnings.append(
            "non-uniform pulse widths: a single calibrated pi operation stretched to different "
            "durations does not give a pi rotation for every width (amplitude recalibration needed)"
        )
    if seq.dt_grid is not None:
        ratio = seq.dt_grid / dt
        if abs(ratio - round(ratio)) > 1e-9 or round(ratio) < 1:
            warnings.append(f"sequence dt_grid {seq.dt_grid} s is not an integer multiple of clock {dt} s")
    instrs: list[Instruction] = []
    el = cfg.qubit_element
    t = 0
    theta = 0.0  # cumulative frame rotation applied so far (rad)
    n_frame = 0

    def frame(delta: float, note: str) -> None:
        nonlocal theta, n_frame
        delta = _wrap_pi(delta)
        if abs(delta) <= cfg.phase_tol_rad:
            return
        instrs.append(Instruction("frame_rotation_2pi", el, t, turns=delta / (2 * math.pi), note=note))
        theta += delta
        n_frame += 1

    for k in range(seq.n + 1):
        if gaps_c[k] > 0:
            instrs.append(Instruction("wait", el, t, cycles=gaps_c[k], note=f"free gap {k}"))
            t += gaps_c[k]
        if k == seq.n:
            break
        phi = float(seq.phases[k])
        frame(cfg.frame_sign * phi - theta, f"set axis for pulse {k} (phi={phi:.6g} rad)")
        instrs.append(Instruction("play", el, t, cycles=widths_c[k], operation=cfg.pi_operation,
                                  axis_phase_rad=phi, note=f"pulse {k}"))
        t += widths_c[k]
    if cfg.restore_frame:
        frame(-theta, "restore element frame to its value at window start")
    if virtual_z_angle is not None:
        frame(-cfg.frame_sign * float(virtual_z_angle),
              f"target-frame virtual-Z correction theta_vz={virtual_z_angle:.6g} rad")

    abs_err = [abs(e) for e in edge_err] + [abs(T_err)]
    width_err = [widths_c[k] * dt - seq.widths[k] for k in range(seq.n)]
    rounding = {
        "mode": "nearest" if cfg.allow_rounding else "strict",
        "T_error_s": T_err,
        "edge_errors_s": edge_err,
        "width_errors_s": width_err,
        "max_abs_edge_error_s": max(abs_err),
        "rms_edge_error_s": math.sqrt(sum(e * e for e in abs_err) / len(abs_err)),
        "n_frame_rotations": n_frame,
        "phase_quantization_bound_rad": n_frame * 2 * math.pi * QM_PHASE_RESOLUTION_TURNS,
    }
    assumptions = {
        "clock_period": f"{dt} s per cycle (4 ns verified from qm-qua 1.4.1 docstrings if unchanged)",
        "min_wait": f"{cfg.min_wait_cycles} cycles -- ASSUMED, UNVERIFIED",
        "min_pulse": f"{cfg.min_pulse_cycles} cycles -- ASSUMED, UNVERIFIED",
        "frame_rotation_duration": "zero -- ASSUMED, verify with QM simulator",
        "frame_sign": f"{cfg.frame_sign} -- REQUIRES HARDWARE CALIBRATION",
        "pi_operation": f"'{cfg.pi_operation}' assumed calibrated pi about X at frame 0 -- PLACEHOLDER",
        "element": f"'{cfg.qubit_element}' -- PLACEHOLDER",
    }
    sched = HardwareSchedule(
        instructions=instrs,
        total_cycles=T_c,
        clock_period_s=dt,
        T_requested_s=seq.T,
        T_scheduled_s=T_c * dt,
        source_label=seq.label,
        rounding=rounding,
        warnings=warnings,
        assumptions=assumptions,
        config=asdict(cfg),
        source_metadata=dict(seq.metadata),
    )
    sched.check()
    return sched
